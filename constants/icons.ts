/**
 * The app's icon vocabulary, drawn by lucide.
 *
 * The key is the name the app writes; the value is the glyph. Ink resolves its
 * own `icon=` slots from this same map, so a name that works in `GIcon` works
 * in `InkButton` and `InkEmptyState` too.
 *
 * `ICONS` is deliberately un-annotated: typing it `Record<string, …>` would
 * collapse `IconName` to `string` and let any name compile, which is how
 * `devices` and `x` shipped as invisible icons.
 */

